"""Run messy requests through the clarification loop, with answers simulated from each expected intent.

Usage: python3 -I scripts/eval_messy.py data/estate.db [data/messy_requests.jsonl] [docs/messy_to_clean.md]
Rules only, no model calls, so a rerun gives the same numbers.
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "backend"))
from reuse_gate.estate import Estate
from reuse_gate.llm import NoLLM
from reuse_gate.pipeline import run_request
from reuse_gate.recommend import Intent, recommend

AS_OF = "2026-11-07"
FIELDS = ("products", "market", "kpis", "kind")


def load(path):
    return [json.loads(line) for line in Path(path).read_text(encoding="utf-8").splitlines() if line.strip()]


def agrees(intent, expected):
    """Which fields match the clean intent. Order does not matter for lists: the decision treats them as sets."""
    same = lambda a, b: set(a) == set(b) if isinstance(a, list) else a == b
    return {k: same(intent[k], expected[k]) for k in FIELDS}


def market_name(est, market):
    return est.markets[market]["market_name"] if market in est.markets else market


def simulate(est, row, result):
    """The answer a requester who wants the expected intent would give to each open question."""
    intent, want = result["intent"], row["expected"]
    proposed = result["pipeline"][0]["output"]["proposed_kpis"]
    out = []
    for q in intent["questions"]:
        field = q["field"]
        if field == "product":
            reply = "yes" if set(intent["products"]) == set(want["products"]) else ("all products" if want["products"] == [est.all_scope] else ", ".join(want["products"]))
        elif field == "market":
            reply = "yes" if intent["market"] == want["market"] else market_name(est, want["market"])
        elif field == "kpi":
            reply = "yes" if set(intent["kpis"] + proposed) == set(want["kpis"]) else ", ".join(want["kpis"])
        elif field in ("scope", "restate"):
            reply = row["clean_text"]
        else:
            reply = "yes"
        out.append({"field": field, "question": q["text"], "answer": reply})
    return out


def unhelpful(est, row, result):
    return [{"field": q["field"], "question": q["text"], "answer": "no idea really"} for q in result["intent"]["questions"] if q["field"] != "scope"] + \
           [{"field": "scope", "question": q["text"], "answer": "dunno"} for q in result["intent"]["questions"] if q["field"] == "scope"]


def run_loop(est, row, reply):
    """Exactly what the front end does: resend the text, the kept answers and the recorded rounds until the loop stops."""
    req = {"request_id": row["id"], "request_text": row["text"], "product_context": est.all_scope, "market_context": None}
    result = first = run_request(est, req, NoLLM(), as_of=AS_OF)
    while result["loop"]["status"] == "asking":
        req = {**req, "request_text": result["text"]}
        result = run_request(est, req, NoLLM(), as_of=AS_OF, answers=(result["answers"] or []) + reply(est, row, result), rounds=result["loop"]["rounds"])
    return first, result


def clean_decision(est, row):
    want = row["expected"]
    rec = recommend(est, Intent(row["id"], row["text"], want["products"], want["market"], want["kpis"], want["kind"]))
    return rec.action, rec.target


def evaluate(est, rows):
    out = []
    for row in rows:
        first, final = run_loop(est, row, simulate)
        _, stuck = run_loop(est, row, unhelpful)
        rec = final["recommendation"]
        out.append({"id": row["id"], "messiness": row["messiness"], "text": row["text"], "first": agrees(first["intent"], row["expected"]),
                    "final": agrees(final["intent"], row["expected"]), "rounds": final["loop"]["rounds_used"], "status": final["loop"]["status"],
                    "questions": sum(len(r["questions"]) for r in final["loop"]["rounds"]), "action": rec["action"], "target": (rec["target"] or {}).get("id"),
                    "clean": clean_decision(est, row), "unhelpful": (stuck["loop"]["status"], stuck["loop"]["rounds_used"], stuck["recommendation"]["action"])})
    return out


def report(rows):
    total = len(rows)
    exact = [r for r in rows if all(r["final"].values())]
    first = sum(all(r["first"].values()) for r in rows)
    same = [r for r in rows if (r["action"], r["target"]) == tuple(r["clean"])]
    rounds = [r["rounds"] for r in rows]
    asked = [r for r in rows if r["unhelpful"][1] > 0]
    by_field = {k: sum(r["final"][k] for r in rows) for k in FIELDS}
    first_field = {k: sum(r["first"][k] for r in rows) for k in FIELDS}
    misses = [r for r in rows if not all(r["final"].values())]
    lines = [
        "# Messy to clean: the clarification loop", "",
        "Generated by `python3 -I scripts/eval_messy.py data/estate.db`. Do not edit by hand. Rules only, no model calls, so a rerun gives the same numbers.", "",
        f"{total} messy prompts in `data/messy_requests.jsonl`, each derived from one of the 10 clean requests, with the clean intent written next to it.",
        "Answers are simulated: a requester who wants the expected intent says yes to a correct proposal and names the value otherwise.", "",
        "## Results", "",
        f"- Clean intent on the first reading, before any question: {first}/{total}",
        f"- Clean intent after the loop: {len(exact)}/{total}",
        f"- Same decision and target as the clean intent gets: {len(same)}/{total}",
        f"- Rounds to clean: mean {sum(rounds) / total:.2f}, maximum {max(rounds)}. " + ", ".join(f"{n} round(s): {rounds.count(n)}" for n in sorted(set(rounds))),
        f"- Ended clear: {sum(r['status'] == 'clear' for r in rows)}/{total}, sent to a person: {sum(r['status'] == 'human_review' for r in rows)}/{total}",
        f"- With a requester who only gives useless answers: {sum(r['unhelpful'][0] == 'human_review' for r in asked)}/{len(asked)} prompts that asked anything went to human_review after 3 rounds, "
        f"and {sum(r['unhelpful'][2] == 'human_review' for r in asked)}/{len(asked)} ended with the action human_review", "",
        "| Field | First reading | After the loop |", "| --- | --- | --- |",
    ]
    lines += [f"| {k} | {first_field[k]}/{total} | {by_field[k]}/{total} |" for k in FIELDS]
    lines += ["", "## Every prompt", "", "| Id | Messiness | Prompt | First reading | Rounds | After the loop | Decision | Same as clean |", "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    for r in rows:
        mark = lambda got: "clean" if all(got.values()) else "wrong: " + ", ".join(k for k, ok in got.items() if not ok)
        lines.append(f"| {r['id']} | {', '.join(r['messiness'])} | {r['text']} | {mark(r['first'])} | {r['rounds']} | {mark(r['final'])} | {r['action']} {r['target'] or ''} | {'yes' if (r['action'], r['target']) == tuple(r['clean']) else 'no'} |")
    lines += ["", "## Misses", ""]
    lines += [f"- {r['id']}: {', '.join(k for k, ok in r['final'].items() if not ok)} stayed wrong after the loop, with no question to catch it." for r in misses] or ["- none"]
    lines += ["", "## How far to trust this", "",
              "- The answers are simulated and always helpful. Real requesters are less tidy, so this is a best case for rounds.",
              "- The vocabulary in `data/catalog.json` (abbreviations, Finnish and German words) was written with these prompts in view, so agreement on unseen prompts will be lower. This set checks that the loop works. It is not a measure of general language coverage.",
              "- The expected intents were written by the same person as the rules. The data pack has no ground truth.",
              "- Misspelled and non-English readings are held as proposals, so they do nothing until the requester confirms them. A wrong reading costs a question and is not silently used.",
              "- The model is off here. On the live API a model reads the first prompt when available and may reword questions, so live numbers can differ."]
    return "\n".join(lines) + "\n"


def main(db, messy="data/messy_requests.jsonl", out="docs/messy_to_clean.md"):
    est = Estate(db)
    text = report(evaluate(est, load(messy)))
    Path(out).write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main(*sys.argv[1:4])
